internal sealed partial class TlsQuicConnection
{
    /// <summary>The largest packet number the peer has acknowledged in the packet number
    /// space (RFC 9000 s12.3) that <paramref name="level"/> belongs to, or
    /// <see langword="null"/> if it has acknowledged nothing there.</summary>
    /// <remarks>The witness for a 1-RTT packet that a peer actually acknowledged: nothing
    /// else this connection exposes moves when an Application-space ACK arrives.</remarks>
    internal ulong? LargestAcknowledged(TlsQuicEncryptionLevel level) => _acks.LargestAcked(level);

    // ========================================================================
    // TASK A3-11 - RFC 9002 s7's SEND GATE, AND THE THREE THINGS IT MUST LET PAST
    // ========================================================================
    //
    // THE HANDOVER THIS CLOSES, IN A3-8's OWN WORDS: "s7's MUST NOT send a packet if it would
    // cause bytes_in_flight to be larger than the congestion window still doesn't gate NEW
    // data. The window is live and every signal reaches it; the gate needs the probe/recovery
    // exceptions threaded through TlsQuicApplicationSendPath.cs". TlsQuicLossDetection.cs's own
    // closing note says the same thing from the other end - "BuildAnswerDatagram and
    // TryBuildApplicationPacket still build without asking".
    //
    // THE SENTENCE, rfc9002-section7-congestion-control.txt lines 46-49, verbatim and complete
    // including the clause that is usually dropped:
    //
    //     An endpoint MUST NOT send a packet if it would cause bytes_in_flight (see
    //     Appendix B.2) to be larger than the congestion window, unless the packet is sent on
    //     a PTO timer expiration (see Section 6.2) or when entering recovery (see
    //     Section 7.3.2).
    //
    // A GATE WITHOUT THOSE TWO EXCEPTIONS IS NOT A STRICTER IMPLEMENTATION OF THIS SENTENCE,
    // IT IS A DEADLOCK. The window closes when bytes are in flight; the bytes leave flight when
    // they are acknowledged, declared lost, or discarded; and a connection whose peer has gone
    // silent learns none of those without sending something. The PTO probe is the thing that
    // makes it learn. Block the probe and the window can never reopen - which is the exact
    // stall RFC 9000 s8.1's anti-deadlock probe exists to break, and which task A3-7 closed.
    //
    // THE FOUR CLASSES OF SEND, AND WHICH SIDE OF THE GATE EACH IS ON:
    //
    //   1. PTO PROBES - EXEMPT, s7's first exception and s7.5 lines 195-196: "Probe packets
    //      MUST NOT be blocked by the congestion controller. A sender MUST however count these
    //      packets as being additionally in flight". EXEMPT BY CONSTRUCTION AND NOT BY A FLAG:
    //      SendOwedProbeAsync and TryBuildProbeDatagram never call this method, so there is no
    //      argument a caller could pass wrongly. The second half of s7.5 was already satisfied
    //      before this task - the probe's datagram goes through RetainSentPackets and
    //      OnPacketSent like every other, so its bytes ARE counted and the window may legally
    //      go negative-headroom afterwards, which s7.5's last sentence explicitly anticipates.
    //
    //   2. THE ONE PACKET ON ENTERING RECOVERY - EXEMPT, s7's second exception, pointing at
    //      s7.3.2 lines 147-153: "Implementations MAY reduce the congestion window immediately
    //      upon entering a recovery period or use other mechanisms, such as Proportional Rate
    //      Reduction [PRR], to reduce the congestion window more gradually. If the congestion
    //      window is reduced immediately, A SINGLE PACKET CAN BE SENT PRIOR TO REDUCTION. This
    //      speeds up loss recovery if the data in the lost packet is retransmitted". That is
    //      B.6's undefined MaybeSendOnePacket, and the controller's own remarks record that it
    //      "is not implemented and the window is reduced immediately, which is the same lines'
    //      first alternative" - the alternative whose next sentence GRANTS this packet. So the
    //      exemption is available to this build precisely because A3-9 reduced immediately.
    //
    //      HOW IT IS DETECTED WITHOUT WIDENING THE SEAM, WHICH IS THE DESIGN CALL HERE.
    //      ITlsQuicCongestionController's CanSend remarks already settle where the exceptions
    //      live: "The two exceptions are the CALLER's ... Putting the exceptions here would
    //      mean this method sometimes answers a question it was not asked". So no eighth member
    //      was added. The signal used instead is one every controller has and the seam already
    //      exposes: CongestionWindowBytes going DOWN. s7.3.2's reduction is the only thing that
    //      lowers a NewReno window apart from s7.6.2's collapse, and a CUBIC or BBR controller
    //      that lowers its window has by the same token entered its own recovery - so the
    //      detection is as portable as the seam is, which a type test on NewReno would not have
    //      been. It grants ONE packet, because s7.3.2 says "a single packet".
    //
    //      s7.6.2's COLLAPSE ALSO LOWERS THE WINDOW AND THEREFORE ALSO GRANTS ONE. That is
    //      named rather than special-cased: B.8 runs the congestion event and the persistent-
    //      congestion collapse in one body, s7.3.2's grant is a MAY in both readings, and one
    //      extra packet at the moment a blackout is declared is the same single packet s7.3.2
    //      licenses - it does not accumulate, because the exemption is consumed on use.
    //
    //   3. ACK-ONLY CONTENT - NEVER GATED, AND NOT AS A FAVOUR. RFC 9002 B.2 lines 507-509:
    //      "Packets only containing ACK frames do not count toward bytes_in_flight", so such a
    //      packet cannot cause bytes_in_flight to be larger than anything and s7's sentence has
    //      no purchase on it. s7.7 lines 353-355 say the same for the pacer: "packets
    //      containing only ACK frames SHOULD therefore not be paced". BOTH ARE STRUCTURAL HERE:
    //      this method is consulted only where the send path is about to add IN-FLIGHT frames,
    //      so a pass whose only output is an ACK never reaches it, and the ACK leaves on time.
    //      That is also the second limb of the anti-deadlock argument - a fully closed window
    //      still acknowledges, so the peer's own window keeps moving.
    //
    //   4. CRYPTO FROM THE TLS ENGINE - NOT GATED, AND THIS IS A CEILING RATHER THAN A CLAIM
    //      OF CONFORMANCE. TlsQuicCryptoDataEvent hands over the only copy of its bytes -
    //      Finding 1 - and BuildAnswerDatagram's caller disposes every result on the way out of
    //      the pump, so a pass that declined to put a CRYPTO frame in a packet would DESTROY
    //      it, not defer it. Gating it needs a send queue for handshake bytes, which is a
    //      feature and not a guard. The exposure is bounded and small: the client's whole
    //      handshake flight is one or two datagrams against an initial window of ten, so the
    //      window cannot close on a path that has only ever sent CRYPTO. Recorded here so that
    //      the next reader does not mistake the absence for an oversight; a A4-era send queue
    //      is what would close it.
    //
    // WHAT IS ON THE GATED SIDE, THEN: A3-8's repair queues (already, since A3-8 - see
    // TakeRepairsInto, which asks CanSend and leaves a refused repair OWED) and this task's
    // addition, the 1-RTT frames TlsQuicStreamSet holds - which is both new stream data and the
    // 1-RTT repairs, since TakePendingFrames drains the two together. THAT IS THE BULK SENDER.
    // Everything a caller of this library can generate in quantity goes through that one queue.
    //
    // A REFUSED SEND IS DEFERRED AND NEVER DROPPED, which is what makes the gate safe to put
    // in front of a queue at all: TakePendingFrames is simply not called, so the frames stay
    // queued in their own order and the next pass offers them again.
    //
    // THE SIZE THIS ASKS ABOUT IS max_datagram_size AND THAT IS AN OVER-ESTIMATE, DELIBERATELY
    // IN THE OPPOSITE DIRECTION FROM A3-8's. TakeRepairsInto passes the sum of the repairs'
    // payloads and its own remarks call that "a lower bound"; a lower bound admits a packet at
    // the boundary that a byte-exact gate would refuse. This asks for a whole datagram, because
    // the quantity s7 is written in IS the datagram - s7.2's initial window is ten of them and
    // its minimum window is two - and because the exact size is TlsQuicPacketBuilder's and does
    // not exist until after the build, by which time the packet number is spent and the frames
    // are taken. Over-estimating can only ever refuse a send s7 would have permitted, which is
    // the direction a MUST NOT should be wrong in.

    /// <summary>RFC 9002 s7's send gate and s7.7's pacer, asked once, before anything that
    /// would put bytes in flight is taken out of a queue.</summary>
    /// <remarks>See this file's A3-11 block for the sentence, the two exceptions, and the four
    /// classes of send.</remarks>
    /// <param name="now">The pump's instant.</param>
    /// <returns>True when in-flight frames may be added to this pass's packet.</returns>
    private bool SendGateAdmits(DateTimeOffset now)
    {
        var bytes = _options.Spec.PaddingTarget;
        var controller = Congestion;
        var window = controller.CongestionWindowBytes;

        // s7's SECOND EXCEPTION, ARMED. The comparison is against the window as it stood the
        // last time this gate ran, so a reduction that happened between two send passes is seen
        // exactly once however many packets were sent in between. First call arms the baseline
        // and grants nothing, which is right: a fresh controller has entered no recovery period.
        if (_windowAtLastGate is { } previous && window < previous)
        {
            _recoveryExemptionOwed = true;
        }

        _windowAtLastGate = window;

        var exempt = false;
        if (!controller.CanSend(bytes))
        {
            if (!_recoveryExemptionOwed)
            {
                SendsRefusedByCongestionWindow++;
                return false;
            }

            exempt = true;
        }

        // s7.7. The rate is read live off the same controller the gate just asked, so a window
        // that moved moves the spacing with it, and the smoothed RTT is the estimator's rather
        // than a second copy.
        if (!Pacer.TryTake(bytes, now, window, _acks.SmoothedRtt))
        {
            SendsDeferredByPacer++;
            return false;
        }

        // s7.3.2's "a single packet can be sent prior to reduction", SPENT ONLY WHEN THE PACKET
        // ACTUALLY LEAVES - which is why the pacer is asked first and this line is last.
        // Consuming it above, before s7.7 had its say, burned a permission on a pass that then
        // did not send: the release pass that followed would find the window still shut, the
        // exemption already gone, and the one packet s7.3.2 grants never sent at all. That is
        // not a conformance failure - the grant is a MAY - but it is the grant not taken, and
        // its whole purpose is to "speed up loss recovery if the data in the lost packet is
        // retransmitted".
        if (exempt)
        {
            _recoveryExemptionOwed = false;
            RecoveryWindowExemptionsUsed++;
        }

        return true;
    }

    private long? _windowAtLastGate;
    private bool _recoveryExemptionOwed;
    private TlsQuicPacer? _pacer;

    /// <summary>This connection's RFC 9002 s7.7 pacer, built from knobs 14 and 15.</summary>
    /// <remarks>CONSTRUCTED ON FIRST USE, for the reason <c>Congestion</c> gives about its own:
    /// a connection that is built and never started should run nothing the spec configured.
    /// </remarks>
    internal TlsQuicPacer Pacer =>
        _pacer ??= new TlsQuicPacer(_options.Spec.Recovery, _options.Spec.PaddingTarget);

    /// <summary>How many send passes RFC 9002 s7's congestion window has refused.</summary>
    /// <remarks>THE WITNESS THAT THE GATE ENGAGED. A transfer that completes completes with no
    /// gate at all, so a test that only watched the transfer would score a build that never
    /// asked. Counts refusals, not questions: an admitted send does not move it.</remarks>
    internal int SendsRefusedByCongestionWindow { get; private set; }

    /// <summary>How many send passes RFC 9002 s7.7's pacer has held back.</summary>
    /// <remarks>The same witness for the pacer, and the reason the live tests can tell pacing
    /// on from pacing off without measuring wall-clock time.</remarks>
    internal int SendsDeferredByPacer { get; private set; }

    /// <summary>How many times RFC 9002 s7's "or when entering recovery" exception has carried
    /// a send past a closed window.</summary>
    internal int RecoveryWindowExemptionsUsed { get; private set; }

    /// <summary>RFC 9002 s7.7's release instant, for
    /// <c>TlsQuicConnection.EarliestDeadline</c>'s earliest-of table.</summary>
    /// <remarks>NULL WHENEVER THE PACER HAS NOT DEFERRED, so the table is unchanged for every
    /// connection that does not pace and for every pass a pacing connection admits - which is
    /// what keeps a build with pacing off byte-for-byte and instant-for-instant identical to
    /// the build before this task.</remarks>
    internal DateTimeOffset? PacingReleaseAt => _pacer?.ReleaseAt;


    /// <summary>Sends whatever is pending without waiting for a datagram to arrive first,
    /// and reports whether anything went out.</summary>
    /// <remarks>
    /// <para>AN ADDITIONAL ENTRY, NOT A REPLACEMENT FOR <see cref="PumpOnceAsync"/>. The
    /// receive-driven loop is still what drives the handshake; this exists because from
    /// 1-RTT onwards the client is the one with something to say first - subsystem C opens an
    /// HTTP/3 control stream and sends SETTINGS before the server has said anything - and a
    /// pump that can only answer cannot do that.</para>
    /// <para>ONE LOOP, ONE THREAD OF CONTROL still holds: this is a call the same caller
    /// makes on the same thread between pumps, not a second pump running beside the first.
    /// </para>
    /// </remarks>
    /// <returns><see langword="true"/> if a datagram was sent.</returns>
    internal async ValueTask<bool> SendPendingAsync(CancellationToken cancellationToken = default)
    {
        EnsureSendable();

        // NO CRYPTO EVENTS, because nothing was received to produce any. Everything else
        // BuildAnswerDatagram does - the pending ACKs at each level, the PATH_RESPONSE - is
        // read from state that is already there.
        return await SendAnswerAsync([], _options.TimeProvider.GetUtcNow(), cancellationToken)
            .ConfigureAwait(false);
    }

    // The three preconditions both entry points share, lifted out of PumpOnceAsync so that
    // one gate guards both rather than two copies drifting apart. The messages are unchanged
    // and the tests that pin them are unchanged with them.
    private void EnsureSendable()
    {
        ObjectDisposedException.ThrowIf(_disposed, this);
        if (!_started)
        {
            throw new InvalidOperationException("Start the connection before pumping it.");
        }
        if (_draining)
        {
            // RFC 9000 s10.2.1 and s10.2.2, the two states this one flag stands for. A4-minimal
            // implements them only as far as "stop sending, stop delivering": there is no timer
            // holding the state for "at least three times the current PTO", because A3 owns the
            // PTO and there is nothing here to hold state FOR - a one-shot attempt has no later
            // packet to attribute. s10.2.1's "sends a packet containing a CONNECTION_CLOSE frame
            // in response to any incoming packet" is deliberately not implemented for the same
            // reason it is rate-limited there: it answers packets, and this connection has
            // stopped reading them.
            throw new InvalidOperationException(
                "This connection is closing or draining (RFC 9000 s10.2), so it neither sends "
                    + "nor delivers. A new attempt is a new connection.");
        }
    }

    /// <summary>Builds the one 1-RTT packet this connection may have to send, or reports that
    /// there is nothing to put in one.</summary>
    /// <remarks>
    /// <para>BUILT AFTER THE LEVEL LOOP RATHER THAN INSIDE IT, AND THAT IS RFC 9000 s12.2
    /// RATHER THAN A PREFERENCE: "packets with a short header (Section 17.3) do not contain a
    /// Length field and so cannot be followed by other packets in the same UDP datagram."
    /// <see cref="TlsQuicDatagramBuilder"/> enforces it and would throw on a datagram that put
    /// this packet anywhere else. The spec's <c>CoalesceAscendingByLevel</c> knob orders the
    /// LONG-header packets - which is the dimension a fingerprint can see - and with it false
    /// the Application level comes FIRST in the descending list, so building this packet in
    /// the loop would hand the datagram builder an illegal order on any answer that also
    /// carried an Initial or Handshake packet. THAT IS REACHABLE FROM A CONFORMING PEER: a
    /// server that retransmits its ack-eliciting Handshake flight coalesced with a 1-RTT
    /// packet leaves this connection owing an ACK at two levels in one answer. Position is
    /// therefore not a knob here, and this method's placement is what makes it unreachable
    /// rather than a guard that has to fire.</para>
    /// <para>NOT async, and it cannot be: <c>TlsQuicWriteKeyMaterial</c> is a ref struct, so
    /// key material never lives in an async state machine.</para>
    /// </remarks>
    private bool TryBuildApplicationPacket(DateTimeOffset now, out TlsQuicPacketToSend packet)
    {
        packet = default;

        // THE KEY CHECK COMES FIRST, AND UNLIKE THE ANSWER LOOP'S IT IS NOT A THROW.
        // BuildAnswerDatagram throws when a level has frames and no write keys because the
        // frames there are CRYPTO - the TLS engine's output, which arriving at a level this
        // connection cannot protect is a sequencing bug worth stopping for. The frames here
        // are ACK and PATH_RESPONSE, both of which are ours to withhold, and RFC 9001 s4.9
        // makes "no keys at this level" the ordinary state rather than an error. s13.2.1's
        // own exception says the same thing in the ACK's case: "an endpoint might not have
        // packet protection keys ... It might therefore buffer them and acknowledge them when
        // the requisite keys become available."
        //
        // AND IT COMES FIRST SO THAT PendingPathResponseData IS NOT CLEARED BY A PACKET THAT
        // WAS NEVER BUILT. RFC 9000 s19.17's MUST is to answer the challenge; dropping the
        // eight bytes on the way to discovering we could not send would turn a deferral into
        // a violation.
        //
        // BOTH THE CHECK AND ITS POSITION ARE UNREACHABLE TODAY AND DELIBERATELY UNWITNESSED,
        // AND THAT IS MEASURED RATHER THAN ASSUMED - mutation rows 3 and 4 both survive the
        // whole gate. Every frame built below exists only because a 1-RTT packet was OPENED,
        // which needs Application READ keys, and CustomTlsQuicClient raises both Application
        // traffic secrets from the one completion result that PumpOnceAsync installs before it
        // sends. So this branch is never taken and the paragraph above is a claim about a
        // state that cannot arise; it is kept because the state becomes reachable the moment
        // anything installs the two directions apart, and it is labelled rather than asserted
        // to be load-bearing.
        if (!_keys.TryGetWriteKeys(TlsQuicEncryptionLevel.Application, out var keys, out _))
        {
            return false;
        }

        var frames = new List<TlsQuicFrame>();

        // The ACK's position is the spec's here for the same reason it is in
        // BuildAnswerDatagram - a knob the connection fixes is a knob task 11 cannot report.
        var hasAck = TryBuildAckFrame(TlsQuicEncryptionLevel.Application, now, out var ack);
        if (hasAck && _options.Spec.AckLeadsInPacket)
        {
            frames.Add(ack);
        }

        if (PendingPathResponseData is { } challenge)
        {
            // RFC 9000 s19.17: "The recipient of this frame MUST generate a PATH_RESPONSE
            // frame (Section 19.18) containing the same Data value." s19.18 makes the two
            // frames' formats identical, so the recorded eight bytes go back out unchanged -
            // re-deriving them would be a second transcription of a value the peer chose.
            //
            // s12.4 Table 3 gives PATH_RESPONSE the row "___1", a 1-RTT packet and nothing
            // else, which is why task 9b could record this and not send it and why the answer
            // is built here rather than beside the record.
            frames.Add(new TlsQuicFrame
            {
                RawType = (ulong)TlsQuicFrameType.PathResponse,
                Data = challenge,
            });

            // CLEARED, AND NOT RETRANSMITTED IF THIS DATAGRAM IS LOST - RFC 9000 s13.3's
            // frame-by-frame loss rules put PATH_RESPONSE among the frames that are not
            // resent. NOT QUOTED, BECAUSE s13.3 IS NOT IN THIS REPO'S REFERENCE CAPTURES:
            // rfc9000-section13-packetization-and-ack-generation.txt stops inside s13.2, so
            // this citation is weaker than the ones around it and is marked as such rather
            // than dressed up with a quotation nobody here can check. The behaviour is also
            // what A4-minimal would do anyway: it has no retransmission at all (that is A3's),
            // so a lost answer is the peer's PATH_CHALLENGE to repeat.
            PendingPathResponseData = null;
        }

        // TASK 14e's STREAM FRAMES, AFTER THE PATH_RESPONSE AND BEFORE THE TRAILING ACK. RFC
        // 9000 s12.4 Table 3 gives STREAM the row "__01", so a 1-RTT packet is where they
        // belong, and TlsQuicFrameLegality.Permits gates that in the builder. The position is
        // NOT a fingerprint knob claiming to be one: AckLeadsInPacket decides whether the ACK
        // leads or trails, and these sit inside whichever bracket that leaves, so both rows of
        // the knob still put the ACK where the knob says.
        //
        // _streams RATHER THAN Streams, because the property builds the set from the peer's
        // budget on first touch and would throw here on a connection whose parameters have not
        // arrived. Nothing is pending on a connection that never opened a stream.
        //
        // A3-11's GATE, AND THIS IS THE LINE A3-8's HANDOVER NAMED. TakePendingFrames drains
        // both this stream set's 1-RTT repairs and its new data, so RFC 9002 s7's MUST NOT and
        // s7.7's pacer are asked once, here, ahead of the take rather than after it - a refused
        // pass leaves every frame queued in its own order and offers it again next time.
        // See SendGateAdmits above for the two exceptions and for what is deliberately not
        // gated.
        //
        // THE ORDER OF THE TWO CONDITIONS IS LOAD-BEARING. HasPendingFrames comes FIRST so that
        // a connection with nothing to send never consults the gate at all: asking would spend
        // the pacer's credit on an empty pass and, worse, would arm a pacing deadline for a
        // datagram that does not exist. It also keeps every ACK-only pass off this path
        // entirely, which is s7.7 lines 353-355 and B.2 lines 507-509 - see the block above.
        if (_streams is { } streams && streams.HasPendingFrames && SendGateAdmits(now))
        {
            // RFC 9000 s14.2: "All QUIC packets that are not sent in a PMTU probe SHOULD be
            // sized to fit within the maximum datagram size to avoid the datagram being
            // fragmented or dropped." THIS LINE IS THAT SENTENCE. Until it existed the take
            // was unbounded - `frames.AddRange(streams.TakePendingFrames())` - and a request
            // body arrived as one STREAM frame in one datagram of whatever size the body
            // happened to be. A 32 KB body produced a 32837-byte datagram, which a DF-set
            // IPv4 socket refuses outright with SocketError.MessageSize.
            //
            // WHAT IS ALREADY IN `frames` IS CHARGED FOR, not assumed away: an ACK and a
            // PATH_RESPONSE may precede the stream data, and both are measured with the same
            // encoder that will write them rather than estimated.
            streams.DatagramPayloadBudget = DatagramPayloadBudget;

            var spent = OneRttPacketOverhead;
            foreach (var already in frames)
            {
                spent += TlsQuicFrames.MeasureFrame(_frameMeasureScratch, already);
            }

            frames.AddRange(streams.TakePendingFrames(DatagramPayloadBudget - spent));
        }

        if (hasAck && !_options.Spec.AckLeadsInPacket)
        {
            frames.Add(ack);
        }

        if (frames.Count == 0)
        {
            return false;
        }

        packet = new TlsQuicPacketToSend
        {
            Plan = ShortHeaderPlan(),
            Frames = frames,
            PacketProtectionCipher = keys.PacketCipher,
            Key = keys.Key.ToArray(),
            Iv = keys.Iv.ToArray(),
            HeaderProtectionCipher = keys.HeaderCipher,
            HeaderProtectionKey = keys.HeaderProtectionKey.ToArray(),
        };
        return true;
    }

    // RFC 9000 s17.3.1's 1-RTT packet. A null Type is what TlsQuicPacketBuilder reads as
    // "short header" (A4 task 14b), and the four fields the long header has and this one does
    // not - Version, Source Connection ID, Token, Length - are set to their absent values
    // rather than left to the spec's knobs, because TlsQuicPacketBuilder.ValidateShortHeaderP
    // lan rejects a plan that asks for a field s17.3.1 does not write.
    private TlsQuicPacketPlan ShortHeaderPlan() => new()
    {
        Type = null,
        Version = 0,
        DestinationConnectionId = _destinationConnectionId,
        SourceConnectionId = default,
        Token = default,
        LengthVarintWidth = TlsQuicVarintWidth.Minimal,

        // RFC 9000 s12.3 gives 0-RTT and 1-RTT one packet number space, which is the space
        // this counter's Application slot is; s12.3 also forbids reusing a number in it.
        PacketNumber = _nextPacketNumber[(int)TlsQuicEncryptionLevel.Application]++,
        PacketNumberEncodedLength = _options.Spec.PacketNumberEncodedLength,
        LargestAcknowledged = _acks.LargestAcked(TlsQuicEncryptionLevel.Application),

        // RFC 9001 s5.4: both are protected bits of the short header. KEY PHASE FOLLOWS THE
        // INSTALLED PHASE, and it is now a value rather than a constant: RFC 9001 s6 toggles
        // it on every key update and TlsQuicKeySet owns which generation the write keys are
        // at. This line USED TO READ `KeyPhase = false` with the reason "TlsQuicKeySet
        // installs every level at phase 0 - key update is out of scope for this phase"; that
        // reason is gone, and reading the phase from the key set is what keeps the bit and the
        // keys from ever disagreeing.
        //
        // SPIN BIT: RFC 9000 s17.4's latency spin bit is a passive-measurement aid, not part
        // of packet processing - a constant zero is the disabled reading, it is what the one
        // other short header in this tree (LoopbackQuicPeer's HANDSHAKE_DONE packet) already
        // writes, and it is not a dimension the fingerprint capture records. The section is
        // cited rather than quoted: rfc9000-packet-formats-and-pn-pseudocode.txt truncates
        // s17.4 mid-sentence, so the endpoint-behaviour paragraph is not checkable from this
        // repo's captures. It is not a TlsQuicConnectionSpec knob, so it is not claimed to be
        // one.
        SpinBit = false,
        KeyPhase = ProtectOneMoreApplicationPacket(),
    };

    // RFC 9001 s6.6: "Endpoints MUST count the number of encrypted packets for each set of
    // keys." Counted HERE, in the one method every 1-RTT packet's plan comes from - all three
    // call sites reach it, and it is already the single place the Application packet number is
    // spent, so a packet that is built and never sent still consumes both.
    //
    // RETURNING THE KEY PHASE IS WHAT MAKES THE COUNT UNSKIPPABLE. A separate void counter
    // beside `KeyPhase = _keys.WriteKeyPhase` could be deleted and every test would still
    // pass; folding the two together means a plan cannot get its phase without being counted.
    private bool ProtectOneMoreApplicationPacket()
    {
        ApplicationPacketsProtectedWithCurrentKeys++;
        return _keys.WriteKeyPhase;
    }
}
