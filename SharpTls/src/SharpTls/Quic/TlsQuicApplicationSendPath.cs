// WHY THIS IS A SEPARATE FILE AND NOT MORE OF TlsQuicConnection.cs. The A4 plan's design
// constraints cap that file at 1000 code lines through task 14 and say, in the same list,
// "Task 14's new concerns do not go in this file. Short headers, 1-RTT sending,
// PATH_RESPONSE and streams are a different packet type and a different lifecycle from the
// handshake this file drives; they land in a sibling file."
//
// AND WHY IT IS A PARTIAL CLASS RATHER THAN A NEW TYPE. The same constraint list rejects
// splitting the connection into separate types, and gives the reason: Retry, close and idle
// timeout "mutate a dozen shared private fields ... and driving them into separate types
// would force every one of them `internal` - trading a long file for a wide mutable surface,
// which is the worse of the two". Everything below reads or writes exactly that state -
// _keys, _acks, _nextPacketNumber, _destinationConnectionId, PendingPathResponseData,
// _draining, _started, _disposed - so a second type would widen precisely the surface that
// argument protects. A partial class is the split that satisfies the file-size constraint
// WITHOUT paying that price, and the measurement the constraint names
// (`grep -vcE '^\s*(//|$)'`) is per file, so it is the honest split rather than a dodge.
//
// WHAT DOES NOT LIVE HERE. The receive side of 1-RTT - opening the packet, dispatching its
// frames, recording the PATH_CHALLENGE - is task 9a-ii's and 9b's and stays in
// TlsQuicConnection.cs beside every other frame it handles. Only the SEND direction moved.
//
// ============================================================================
// THE DELAYED-ACK TIMER: A DECISION, NOT A SILENCE
// ============================================================================
//
// A4's "Not in this phase" table carried the row "Delayed-ACK timer and max_ack_delay
// honouring for 1-RTT | A4-complete or A3 | s13.2.1 requires Initial and Handshake ACKs
// immediately, and minimal sends no 1-RTT data, so the timer has no customer yet". The
// second half of that reason stopped being true the moment this file existed, so the row is
// re-decided here rather than left standing on a premise this task removed.
//
// THE DECISION: ACKNOWLEDGE IMMEDIATELY, AT EVERY LEVEL, DELIBERATELY. No timer is added,
// and max_ack_delay is honoured by being beaten rather than by being scheduled against.
//
//   (a) IMMEDIATE SATISFIES THE MUST OUTRIGHT. s13.2.1: "An endpoint MUST acknowledge all
//      ack-eliciting Initial and Handshake packets immediately and all ack-eliciting 0-RTT
//      and 1-RTT packets within its advertised max_ack_delay." A delay of zero is within
//      every advertised value, so the deadline half of the MUST is met by construction and
//      cannot be missed by a scheduling bug. s13.2.1 states max_ack_delay as a CEILING - "an
//      endpoint promises to never intentionally delay acknowledgments of an ack-eliciting
//      packet by more than the indicated value" - not as a target to spend.
//   (b) THE COST s13.2.1 WARNS ABOUT CANNOT ARISE HERE. Its opening balances "frequent
//      feedback from a receiver" against "excessive load generated by a receiver that sends
//      an ACK frame in response to every ack-eliciting packet". This connection sends at
//      most one datagram per datagram received (SendAnswerAsync is called once per pump), so
//      the ACK rides in an answer that was being built anyway; delaying it would remove no
//      packet from the wire, only add latency. The related MUST - "an endpoint MUST NOT send
//      more than one such packet in response to receiving an ack-eliciting packet" - is met
//      by the same one-answer-per-pump shape.
//   (c) A TIMER IS AN ARCHITECTURE CHANGE, NOT A TUNING KNOB. TlsQuicConnection's remarks
//      open with "ONE LOOP, ONE THREAD OF CONTROL" and name it as what satisfies
//      CustomTlsQuicClient's and TlsQuicPacketReceiver's shared-state requirements. A
//      delayed ACK has to fire without a datagram to trigger it, which means either a second
//      thread of control or a timeout woven into the receive await - the first breaks that
//      invariant, and the second is loss-recovery scheduling, which is A3's.
//
//      AND A3 HAS NOW BUILT IT, SO HALF OF (c) IS SPENT. Task A3-5 wove the timeout into the
//      receive await, on the injected TimeProvider, without a second thread: EarliestDeadline
//      in TlsQuicConnection.cs picks the nearest of the handshake deadline, RFC 9000 s10.1's
//      idle timeout and RFC 9002 A.8's loss detection timer, and a wake on the third returns
//      an empty receive result so the pump runs its ordinary send pass with no datagram
//      received. WHAT SURVIVES OF (c) IS THE HALF THAT MATTERED: it is an architecture
//      change, it was sequenced alone for exactly that reason, and it was not A4's to make.
//      What no longer follows from (c) is that the mechanism is unavailable.
//   (d) IT COSTS NOTHING WE MEASURE. The ack_delay this connection reports is already zero
//      for the reason PumpOnceAsync's "ONE INSTANT PER PUMP" note gives, and with an
//      immediate ACK that zero is EXACT rather than merely safe in one direction.
//
// (The four points are lettered rather than numbered so that this file's ledger greps, which
// anchor on `^// +[0-9]+\. `, cannot match them.)
//
// SO THE ROW IS NOT DEFERRED, IT IS CLOSED FOR A4: the timer is not missing work, it is work
// this shape does not need. A4-complete owns it again only if it adds a send path that runs
// between received datagrams often enough for batching to remove packets rather than add
// delay - which is the same condition under which s13.2.1's balance argument starts to bite.
//
// THAT CONDITION IS NOW SATISFIED, AND THE ROW IS REOPENED RATHER THAN LEFT STANDING ON A
// PREMISE THAT HAS GONE. A3-5's wake-on-deadline entry IS a send path that runs between
// received datagrams: PumpOnceAsync now reaches SendAnswerAsync with no datagram received at
// all, so (b)'s "this connection sends at most one datagram per datagram received" has stopped
// being true of it. WHAT THAT DOES AND DOES NOT DECIDE. It does not make an immediate ACK
// wrong - a delay of zero still satisfies s13.2.1's MUST outright, and (a) and (d) are
// untouched. It removes the ARGUMENT in (b) and the OBSTACLE in (c), which together were the
// whole reason the question was closed rather than weighed. Weighing it is
// TlsQuicRecoverySpec.AckPolicy - knob 12 - and A3-12's readout, and it is deliberately NOT
// A3-5's: the timer weave was sequenced alone precisely so that a failure after it is
// attributable to the weave and not to an ACK policy bundled with it. Until a knob says
// otherwise, this connection still acknowledges immediately at every level.
//
// AND A3-11 CONSIDERED IT AND DECLINED IT, WHICH IS RECORDED HERE RATHER THAN LEFT AS A THIRD
// SILENCE. A3-11 added the fourth entry to EarliestDeadline's table, so the mechanism a delayed
// ACK needs now exists twice over and the OBSTACLE in (c) is gone for good. The reason knob 12
// is still unread is not availability, it is that it is a DIFFERENT SENTENCE. RFC 9002 s7.7's
// only word about acknowledgements is lines 353-355 - "packets containing only ACK frames
// SHOULD therefore not be paced" - which is a rule about NOT delaying them, and this task
// implements it structurally by never consulting the pacer on an ACK-only pass. Wiring knob 12
// would DELAY them, on RFC 9000 s13.2.1's authority and not RFC 9002 s7.7's, and it changes how
// many ACK packets leave rather than when a data packet does. Bundling the two would have made
// a failure in either attributable to neither - which is (c)'s own argument, one task later.
// The knob is therefore read by nothing ON THIS PATH, and that is a decision with a reason
// rather than a gap: it belongs to whoever owns s13.2.1's timer.
//
// AND TASK A3-13 TOOK IT, which is recorded here because this paragraph is the reason it was
// A3-13's to take and not A3-11's. The reader is TlsQuicAckTracker.IsWithheldAt, and the
// mechanism that releases a held ACK is TlsQuicConnection's fourth TlsQuicDeadlineKind,
// DelayedAck. NOTHING IN THIS FILE CHANGED FOR THAT, and the split above is why: what A3-13
// delays is the ACK itself, on s13.2.1's authority, and what this path still declines to do is
// consult the pacer on an ACK-only pass, on s7.7's. Two sentences, two owners, two tasks.
//
// ONE CONSEQUENCE IS A KNOWN CEILING RATHER THAN AN OMISSION, and TlsQuicAckTracker carries it
// in full next to IsWithheldAt: because the 1-RTT send path reaches TryBuildAck through the
// NON-force overload, a held ACK is not picked up by a data packet that happens to leave inside
// the 25 ms bound. Routing it through `force` would change the SHIPPED DEFAULT's emitted bytes,
// and default parity outranks a SHOULD whose bound is already met.
//
// The value the knob ships with is a separate question from whether anything reads it, and that
// question is still open: A3-12's readout must render it as UNVERIFIED either way.

